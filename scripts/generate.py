"""Regenerates the clients in src/ from the API descriptions listed in apis.yaml.

    uv run python scripts/generate.py           # from the committed specs in specs/
    uv run python scripts/generate.py --fetch   # download the latest specs first
    uv run python scripts/generate.py --only graphql

Never edit generated code by hand: change apis.yaml, the GraphQL operations in operations/,
the auth classes in src/github_apiroute/auth.py, or apiroute itself, then regenerate. The
Build workflow runs this with --fetch every week and commits whatever changes.

Fetching a GraphQL schema introspects its endpoint, sending the apis.yaml entry's
spec_headers with ${VAR}s filled from the environment (GITHUB_TOKEN for GitHub).
"""

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

import httpx
import yaml

ROOT = Path(__file__).resolve().parent.parent
MARKER = "# Generated by scripts/generate.py from apis.yaml. Do not edit: regenerate instead."


def main() -> int:
    arguments = _parser().parse_args()
    config = yaml.safe_load((ROOT / "apis.yaml").read_text())
    apis = [api for api in config["apis"] if not arguments.only or api["name"] in arguments.only]
    if arguments.only and len(apis) != len(arguments.only):
        print(f"unknown API name in {arguments.only}", file=sys.stderr)
        return 1
    package_dir = ROOT / "src" / config["package"]
    for api in apis:
        spec = _spec_path(api)
        if arguments.fetch:
            _fetch(api, spec)
        _generate(api, spec, package_dir)
    _write_group_packages(config, package_dir)
    _write_readme_table(config)
    return 0


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--fetch", action="store_true", help="download the latest specs first")
    parser.add_argument("--only", nargs="+", metavar="NAME", help="only these APIs (by name)")
    return parser


SUFFIXES = {"openapi": ".json", "wsdl": ".wsdl", "graphql": ".graphql"}


def _spec_path(api: dict) -> Path:
    return ROOT / "specs" / f"{api['name']}{SUFFIXES[api['format']]}"


def _fetch(api: dict, spec: Path) -> None:
    """Saves the spec as published. JSON is re-indented so that a reformatted upload doesn't
    show up as a change; key order is kept, since the generator follows it. A GraphQL schema
    is introspected and saved as SDL, which diffs well."""
    if api["format"] == "graphql":
        _fetch_schema(api, spec)
        return
    response = httpx.get(api["spec"], follow_redirects=True, timeout=60)
    response.raise_for_status()
    if api["format"] == "openapi":
        document = response.json()  # an HTML error page would fail here, not later
        if "openapi" not in document and "swagger" not in document:
            raise ValueError(f"{api['name']}: {api['spec']} isn't an OpenAPI document")
        text = json.dumps(document, indent=2, ensure_ascii=False) + "\n"
    else:
        text = response.text
        if "definitions" not in text[:2000]:
            raise ValueError(f"{api['name']}: {api['spec']} isn't a WSDL document")
    spec.parent.mkdir(exist_ok=True)
    spec.write_text(text)
    print(f"fetched {api['name']}")


def _fetch_schema(api: dict, spec: Path) -> None:
    command = ["apiroute", "fetch-schema", api["spec"], "-o", str(spec)]
    for name, value in api.get("spec_headers", {}).items():
        command += ["-H", f"{name}: {_from_environment(value)}"]
    spec.parent.mkdir(exist_ok=True)
    subprocess.run(command, check=True)  # the token is only ever on the command line


def _from_environment(value: str) -> str:
    """${VAR} replaced by the environment variable's value; a missing one is an error."""

    def lookup(match: re.Match) -> str:
        name = match.group(1)
        if name not in os.environ:
            raise KeyError(f"{name} isn't set; it's needed to fetch the schema")
        return os.environ[name]

    return re.sub(r"\$\{(\w+)\}", lookup, value)


def _generate(api: dict, spec: Path, package_dir: Path) -> None:
    out = package_dir.joinpath(*api["module"].split("."))
    command = [
        "apiroute",
        "generate",
        api["format"],
        str(spec),
        "-o",
        str(out),
        "--client-name",
        api["client"],
    ]
    if api.get("models", True):
        command.append("--models")
    if api.get("base_class"):
        command += ["--base-class", api["base_class"]]
    if api["format"] == "graphql":
        command += ["--operations", str(ROOT / api["operations"]), "--endpoint", api["endpoint"]]
        for name, target in api.get("scalars", {}).items():
            command += ["--scalar", f"{name}={target}"]
        if api.get("persisted_queries"):
            command.append("--persisted-queries")
    subprocess.run(command, check=True)


def _write_group_packages(config: dict, package_dir: Path) -> None:
    """buy/, sell/, ...: plain packages holding the generated clients."""
    groups: dict[str, list[dict]] = {}
    for api in config["apis"]:
        parts = api["module"].split(".")
        if len(parts) > 1:
            groups.setdefault(parts[0], []).append(api)
    for group, apis in groups.items():
        listing = "\n".join(f"- {api['module']}: {api['title']}" for api in apis)
        (package_dir / group / "__init__.py").write_text(
            f'{MARKER}\n"""GitHub {group} APIs:\n\n{listing}\n"""\n'
        )


def _write_readme_table(config: dict) -> None:
    """The README's table of APIs, between its apis:start and apis:end markers."""
    readme = ROOT / "README.md"
    text = readme.read_text()
    start, end = "<!-- apis:start -->", "<!-- apis:end -->"
    if start not in text or end not in text:
        return
    rows = ["| API | Import | Docs |", "| --- | --- | --- |"]
    for api in config["apis"]:
        module = f"{config['package']}.{api['module']}"
        rows.append(
            f"| {api['title']} | `from {module} import {api['client']}` | [docs]({api['docs']}) |"
        )
    table = "\n".join(rows)
    before, rest = text.split(start, 1)
    after = rest.split(end, 1)[1]
    readme.write_text(f"{before}{start}\n{table}\n{end}{after}")


if __name__ == "__main__":
    sys.exit(main())
